    private void construirInterfaz() {
        setLayout(new BorderLayout());
 
        JLabel titulo = new JLabel("Armonía y Cris");
        titulo.setFont(titulo.getFont().deriveFont(Font.BOLD, 18f));
        JButton btnVelas = new JButton("Velas e inventario");
        JButton btnClientes = new JButton("Clientes");
        JButton btnVentas = new JButton("Ventas");
 
        JPanel barra = new JPanel(new FlowLayout(FlowLayout.LEFT, 12, 8));
        barra.add(titulo);
        barra.add(btnVelas);
        barra.add(btnClientes);
        barra.add(btnVentas);
        add(barra, BorderLayout.NORTH);
 
        cartas = new CardLayout();
        contenedor = new JPanel(cartas);
        contenedor.setBorder(BorderFactory.createEmptyBorder(0, 8, 8, 8));
        contenedor.add(new VistaVela(inventario), VELAS);
        contenedor.add(new VistaCliente(clientes), CLIENTES);
        contenedor.add(new VistaVenta(inventario, clientes, ventas), VENTAS);
        add(contenedor, BorderLayout.CENTER);
 
        btnVelas.addActionListener(e -> cartas.show(contenedor, VELAS));
        btnClientes.addActionListener(e -> cartas.show(contenedor, CLIENTES));
        btnVentas.addActionListener(e -> cartas.show(contenedor, VENTAS));
 
        cargarDatosDePrueba(); // BORRA esta línea cuando ya tengas Modelo y Controlador
    }
    
