    private void construirInterfaz() {
        setLayout(new BorderLayout(10, 10));
        add(crearPanelFormulario(), BorderLayout.NORTH);
        add(new JScrollPane(new JTable(clientes)), BorderLayout.CENTER);
    }
    
    private JPanel crearPanelFormulario() {
        JPanel panel = new JPanel(new GridLayout(3, 2, 5, 5));
        panel.setBorder(BorderFactory.createEmptyBorder(10, 10, 0, 10));
 
        txtNombre = new JTextField();
        txtTelefono = new JTextField();
        btnGuardar = new JButton("Guardar cliente");
 
        panel.add(new JLabel("Nombre:"));   panel.add(txtNombre);
        panel.add(new JLabel("Teléfono:")); panel.add(txtTelefono);
        panel.add(new JLabel(""));          panel.add(btnGuardar);
 
        btnGuardar.addActionListener(e -> guardarCliente());
        return panel;
    }
    // controlador
    private void guardarCliente() {

    String nombre = txtNombre.getText();
    String telefono = txtTelefono.getText();

    String error = controlador.guardarCliente(nombre, telefono);

    if (error != null) {
        aviso(error);
        return;
    }

    JOptionPane.showMessageDialog(
        this,
        "Cliente guardado correctamente.",
        "Registro exitoso",
        JOptionPane.INFORMATION_MESSAGE
    );

    txtNombre.setText("");
    txtTelefono.setText("");
    txtNombre.requestFocus();
}
    
    private void aviso(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Datos incorrectos", JOptionPane.WARNING_MESSAGE);
    }

