    private void construirInterfaz() {
        setLayout(new BorderLayout(10, 10));
        add(crearPanelFormulario(), BorderLayout.NORTH);
        add(crearPanelTabla(), BorderLayout.CENTER);
    }
    
    private JPanel crearPanelFormulario() {
        JPanel panel = new JPanel(new GridLayout(6, 2, 5, 5));
        panel.setBorder(BorderFactory.createEmptyBorder(10, 10, 0, 10));
 
        txtNombre = new JTextField();
        cmbTipo = new JComboBox<>(new String[]{"Aromática", "Decorativa"});
        txtPrecio = new JTextField();
        txtCantidad = new JTextField();
        txtExtra = new JTextField();
        lblExtra = new JLabel("Aroma:");
        btnGuardar = new JButton("Guardar vela");
 
        panel.add(new JLabel("Nombre:"));   panel.add(txtNombre);
        panel.add(new JLabel("Tipo:"));     panel.add(cmbTipo);
        panel.add(new JLabel("Precio:"));   panel.add(txtPrecio);
        panel.add(new JLabel("Cantidad:")); panel.add(txtCantidad);
        panel.add(lblExtra);                panel.add(txtExtra);
        panel.add(new JLabel(""));          panel.add(btnGuardar);
 
        cmbTipo.addActionListener(e ->
                lblExtra.setText(cmbTipo.getSelectedIndex() == 0 ? "Aroma:" : "Diseño:"));
        btnGuardar.addActionListener(e -> guardarVela());
 
        return panel;
    }
    
    private JScrollPane crearPanelTabla() {
        tabla = new JTable(inventario);
 
        // HU2 - criterio 2: las velas agotadas se ven en rojo; el precio se muestra como dinero
        tabla.setDefaultRenderer(Object.class, new DefaultTableCellRenderer() {
            @Override
            public Component getTableCellRendererComponent(JTable t, Object valor,
                    boolean seleccionada, boolean foco, int fila, int columna) {
                Component c = super.getTableCellRendererComponent(t, valor, seleccionada, foco, fila, columna);
                if (columna == COL_PRECIO && valor instanceof Double) {
                    setText(moneda((Double) valor));
                }
                boolean agotada = "AGOTADA".equals(t.getValueAt(fila, COL_ESTADO));
                if (seleccionada) {
                    c.setForeground(t.getSelectionForeground());
                } else {
                    c.setForeground(agotada ? Color.RED : t.getForeground());
                }
                return c;
            }
        });
        return new JScrollPane(tabla);
    }
    
    private void guardarVela() {
        String nombre = txtNombre.getText().trim();
        String tipo = (String) cmbTipo.getSelectedItem();
        String extra = txtExtra.getText().trim();
 
        if (nombre.isEmpty()) {
            aviso("El nombre de la vela no puede estar vacío.");
            return;
        }
        if (extra.isEmpty()) {
            aviso("Escribe el " + (cmbTipo.getSelectedIndex() == 0 ? "aroma" : "diseño") + " de la vela.");
            return;
        }
        if (existe(nombre)) {
            aviso("Ya existe una vela con ese nombre.");
            return;
        }
 
        try {
            double precio = Double.parseDouble(txtPrecio.getText().trim());
            int cantidad = Integer.parseInt(txtCantidad.getText().trim());
            if (Double.isNaN(precio) || Double.isInfinite(precio)) {
                throw new NumberFormatException();
            }
            // HU1 - criterio 1: negativos no se guardan
            if (precio < 0 || cantidad < 0) {
                aviso("El precio y la cantidad no pueden ser negativos.");
                return;
            }
            
            inventario.addRow(new Object[]{nombre, tipo, extra, precio, cantidad, estadoDe(cantidad)});
            limpiarCampos();
        } catch (NumberFormatException ex) {
            // HU1 - criterio 1: letras en el precio o la cantidad
            aviso("El precio y la cantidad deben ser números (el precio con punto decimal, la cantidad entera).");
        }
    }
 
    private boolean existe(String nombre) {
        for (int i = 0; i < inventario.getRowCount(); i++) {
            if (nombre.equalsIgnoreCase((String) inventario.getValueAt(i, COL_NOMBRE))) {
                return true;
            }
        }
        return false;
    }
 
    private void limpiarCampos() {
        txtNombre.setText("");
        txtPrecio.setText("");
        txtCantidad.setText("");
        txtExtra.setText("");
        txtNombre.requestFocus();
    }
    
    private void aviso(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Datos incorrectos", JOptionPane.WARNING_MESSAGE);
    }
    
    public static String estadoDe(int cantidad) {
        return cantidad == 0 ? "AGOTADA" : "Disponible";
    }
    
    public static String moneda(double valor) {
        return String.format(Locale.forLanguageTag("es-CO"), "$%,.0f", valor);
    }
    
