    private void agregarAlCarrito() {
        int fila = cmbVela.getSelectedIndex();
        if (fila < 0) {
            aviso("No hay velas registradas.");
            return;
        }
        try {
            int cantidad = Integer.parseInt(txtCantidad.getText().trim());
            if (cantidad <= 0) {
                aviso("La cantidad debe ser mayor que cero.");
                return;
            }
            int disponible = disponible(fila);
            int yaEnCarrito = cantidadEnCarrito(fila);
            if (yaEnCarrito + cantidad > disponible) {
                aviso("No hay suficientes unidades de " + nombreVela(fila)
                        + ". Disponibles: " + disponible
                        + " (ya en el carrito: " + yaEnCarrito + ").");
                return;
            }
            double precio = (Double) inventario.getValueAt(fila, VistaVela.COL_PRECIO);
            carrito.add(new ItemCarrito(fila, nombreVela(fila), precio, cantidad));
            refrescarCarrito();
            txtCantidad.setText("");
        } catch (NumberFormatException ex) {
            aviso("La cantidad debe ser un número entero.");
        }
    }
 
    private void quitarDelCarrito() {
        int fila = tablaCarrito.getSelectedRow();
        if (fila < 0) {
            aviso("Selecciona una línea del carrito para quitarla.");
            return;
        }
        carrito.remove(fila);
        refrescarCarrito();
    }
    
    private void registrarVenta() {
        int filaCliente = cmbCliente.getSelectedIndex();
        if (filaCliente < 0) {
            aviso("Registra y selecciona un cliente primero.");
            return;
        }
        if (carrito.isEmpty()) {
            aviso("Agrega al menos una vela al carrito.");
            return;
        }
        // Se valida todo antes de descontar
        for (ItemCarrito item : carrito) {
            if (cantidadEnCarrito(item.fila) > disponible(item.fila)) {
                aviso("No hay suficientes unidades de " + item.nombre
                        + " (disponibles: " + disponible(item.fila) + ").");
                return;
            }
        }
        
        double total = 0;
        StringBuilder detalle = new StringBuilder();
        for (ItemCarrito item : carrito) {
            int nueva = disponible(item.fila) - item.cantidad;
            inventario.setValueAt(nueva, item.fila, VistaVela.COL_CANTIDAD);              // HU5 - criterio 1
            inventario.setValueAt(VistaVela.estadoDe(nueva), item.fila, VistaVela.COL_ESTADO);
            total += item.subtotal();
            if (detalle.length() > 0) {
                detalle.append("; ");
            }
            detalle.append(item.nombre).append(" x").append(item.cantidad);
        }
        // Actualizar las cantidades en el archivo velas.txt
String resultado = controladorVela.actualizarCantidadArchivo();

if (resultado != null) {
    JOptionPane.showMessageDialog(
            this,
            resultado,
            "Error",
            JOptionPane.ERROR_MESSAGE
    );
    return;
}
        String cliente = (String) clientes.getValueAt(filaCliente, VistaCliente.COL_NOMBRE);
        ventas.addRow(new Object[]{LocalDateTime.now().format(FECHA), cliente, detalle.toString(), total});
        // Conectar con el controlador para guardar las ventas
        try {

             controladorVenta.guardarVentas(ventas);

        } catch (IOException ex) {

            JOptionPane.showMessageDialog(
            this,
            "Error al guardar las ventas: " + ex.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
            );
        }
        
        JOptionPane.showMessageDialog(this,
                "Venta registrada.\nTotal: " + VistaVela.moneda(total),
                "Venta", JOptionPane.INFORMATION_MESSAGE);
        carrito.clear();
        refrescarCarrito();
    }
 
    private void refrescarCarrito() {
        modeloCarrito.setRowCount(0);
        double total = 0;
        for (ItemCarrito item : carrito) {
            modeloCarrito.addRow(new Object[]{
                item.nombre,
                VistaVela.moneda(item.precio),
                item.cantidad,
                VistaVela.moneda(item.subtotal())
            });
            total += item.subtotal();
        }
        lblTotal.setText("Total: " + VistaVela.moneda(total));
    }
    
    private JPanel crearPanelHistorial() {
        JPanel panel = new JPanel(new BorderLayout(10, 10));
        panel.setBorder(BorderFactory.createEmptyBorder(10, 10, 10, 10));
 
        modeloHistorial = new DefaultTableModel(COLUMNAS, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
        panel.add(new JScrollPane(new JTable(modeloHistorial)), BorderLayout.CENTER);
 
        lblTotalDia = new JLabel("Total vendido hoy: " + VistaVela.moneda(0));
        JPanel inferior = new JPanel(new FlowLayout(FlowLayout.RIGHT, 15, 5));
        inferior.add(lblTotalDia);
        panel.add(inferior, BorderLayout.SOUTH);
        return panel;
    }
    
    private void refrescarHistorial() {
        modeloHistorial.setRowCount(0);
        String hoy = LocalDate.now().format(SOLO_DIA);
        double sumaDia = 0;
        for (int i = 0; i < ventas.getRowCount(); i++) {
            String fecha = (String) ventas.getValueAt(i, 0);
            if (!fecha.startsWith(hoy)) {
                continue;
            }
            double total = (Double) ventas.getValueAt(i, 3);
            modeloHistorial.addRow(new Object[]{
                fecha, ventas.getValueAt(i, 1), ventas.getValueAt(i, 2), VistaVela.moneda(total)
            });
            sumaDia += total;
        }
        lblTotalDia.setText("Total vendido hoy: " + VistaVela.moneda(sumaDia));
    }
    
    private void recargarCombos() {
        int ic = cmbCliente.getSelectedIndex();
        cmbCliente.removeAllItems();
        for (int i = 0; i < clientes.getRowCount(); i++) {
            cmbCliente.addItem(clientes.getValueAt(i, VistaCliente.COL_NOMBRE)
                    + " - " + clientes.getValueAt(i, VistaCliente.COL_TELEFONO));
        }
        if (ic >= 0 && ic < cmbCliente.getItemCount()) {
            cmbCliente.setSelectedIndex(ic);
        }
 
        int iv = cmbVela.getSelectedIndex();
        cmbVela.removeAllItems();
        for (int i = 0; i < inventario.getRowCount(); i++) {
            cmbVela.addItem(inventario.getValueAt(i, VistaVela.COL_NOMBRE)
                    + " (" + inventario.getValueAt(i, VistaVela.COL_TIPO) + ": "
                    + inventario.getValueAt(i, VistaVela.COL_DETALLE) + ") - "
                    + VistaVela.moneda((Double) inventario.getValueAt(i, VistaVela.COL_PRECIO))
                    + " - disp: " + inventario.getValueAt(i, VistaVela.COL_CANTIDAD));
        }
        if (iv >= 0 && iv < cmbVela.getItemCount()) {
            cmbVela.setSelectedIndex(iv);
        }
    }
    
    private String nombreVela(int fila) {
        return (String) inventario.getValueAt(fila, VistaVela.COL_NOMBRE);
    }
    
    private int disponible(int fila) {
        return (Integer) inventario.getValueAt(fila, VistaVela.COL_CANTIDAD);
    }
    
    private int cantidadEnCarrito(int fila) {
        int suma = 0;
        for (ItemCarrito item : carrito) {
            if (item.fila == fila) {
                suma += item.cantidad;
            }
        }
        return suma;
    }
    
    private void aviso(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Aviso", JOptionPane.WARNING_MESSAGE);
    }
    
