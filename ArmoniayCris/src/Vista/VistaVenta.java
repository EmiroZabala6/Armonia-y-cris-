    private static class ItemCarrito {
        final int fila;          // fila de la vela en el inventario
        final String nombre;
        final double precio;
        final int cantidad;
 
        ItemCarrito(int fila, String nombre, double precio, int cantidad) {
            this.fila = fila;
            this.nombre = nombre;
            this.precio = precio;
            this.cantidad = cantidad;
        }
 
        double subtotal() {
            return precio * cantidad;
        }
    }
     
